package artifactstorage

import (
	"fmt"
	"sync"
)

// Registry maps backend names to Provider instances. It is safe for
// concurrent use and allows additional backends (S3, GCS, PVC) to be
// registered without API changes.
type Registry struct {
	mu        sync.RWMutex
	providers map[string]Provider
}

// NewRegistry creates an empty provider registry.
func NewRegistry() *Registry {
	return &Registry{
		providers: make(map[string]Provider),
	}
}

// Register adds a provider to the registry. It returns an error if a
// provider with the same name is already registered.
func (r *Registry) Register(p Provider) error {
	r.mu.Lock()
	defer r.mu.Unlock()

	name := p.Name()
	if _, exists := r.providers[name]; exists {
		return fmt.Errorf("artifact storage provider %q is already registered", name)
	}
	r.providers[name] = p
	return nil
}

// Get returns the provider registered under the given name, or an error
// if no such provider exists.
func (r *Registry) Get(name string) (Provider, error) {
	r.mu.RLock()
	defer r.mu.RUnlock()

	p, ok := r.providers[name]
	if !ok {
		return nil, fmt.Errorf("unknown artifact storage backend %q", name)
	}
	return p, nil
}

// List returns the names of all registered providers.
func (r *Registry) List() []string {
	r.mu.RLock()
	defer r.mu.RUnlock()

	names := make([]string, 0, len(r.providers))
	for name := range r.providers {
		names = append(names, name)
	}
	return names
}
